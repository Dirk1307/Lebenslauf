// Optional authoring step only. Hosting still copies the committed static files.
const fs = require('node:fs/promises');
const path = require('node:path');
const QRCode = require('qrcode');
const {chromium} = require('playwright');
const root = path.resolve(__dirname, '..');
const escapeHTML = value => value.replaceAll('&', '&amp;').replaceAll('"', '&quot;').replaceAll('<', '&lt;').replaceAll('>', '&gt;');
const escapeVCF = value => value.replaceAll('\\', '\\\\').replace(/\r?\n/g, '\\n').replaceAll(';', '\\;').replaceAll(',', '\\,');
function fold(line) {
  let output = '', chunk = '';
  for (const char of line) {
    if (Buffer.byteLength(chunk + char) > 75) { output += chunk + '\r\n'; chunk = ' ' + char; }
    else chunk += char;
  }
  return output + chunk;
}
(async () => {
  const profile = JSON.parse(await fs.readFile(path.join(root, 'site-profile.json'), 'utf8'));
  const website = new URL(profile.website);
  if (website.protocol !== 'https:' || website.username || website.password || website.search || website.hash || website.pathname !== '/') throw Error('Use the confirmed HTTPS root address without tracking parameters.');
  const name = `${profile.firstName} ${profile.lastName}`;
  const htmlFile = path.join(root, 'index.html');
  let html = await fs.readFile(htmlFile, 'utf8');
  if (!html.includes(`mailto:${profile.email}`) || !html.includes(profile.linkedin)) throw Error('Profile must agree with the approved website contact details.');
  const title = html.match(/<title>([^<]+)<\/title>/)[1];
  const description = html.match(/<meta name="description" content="([^"]+)"/)[1];
  const image = new URL('assets/dirk-herrmann-vorschau.png', website).href;
  const metadata = [
    '<!-- Digital business card metadata: generated by npm run card:prepare -->',
    `<link rel="canonical" href="${website.href}">`,
    '<meta property="og:type" content="website">',
    '<meta property="og:locale" content="de_DE">',
    `<meta property="og:site_name" content="${escapeHTML(name)}">`,
    `<meta property="og:title" content="${escapeHTML(title)}">`,
    `<meta property="og:description" content="${description}">`,
    `<meta property="og:url" content="${website.href}">`,
    `<meta property="og:image" content="${image}">`,
    '<meta property="og:image:type" content="image/png">',
    '<meta property="og:image:width" content="1200">',
    '<meta property="og:image:height" content="630">',
    `<meta property="og:image:alt" content="${escapeHTML(name)} – Klar denken. Weiter machen. Porträt und Marketing-Schwerpunkte.">`,
    '<meta name="twitter:card" content="summary_large_image">',
    `<meta name="twitter:title" content="${escapeHTML(title)}">`,
    `<meta name="twitter:description" content="${description}">`,
    `<meta name="twitter:image" content="${image}">`,
    `<meta name="twitter:image:alt" content="${escapeHTML(name)} – Klar denken. Weiter machen.">`,
    '<!-- End digital business card metadata -->'
  ].join('\n');
  const existing = /<!-- Digital business card metadata:[\s\S]*?<!-- End digital business card metadata -->/;
  html = existing.test(html) ? html.replace(existing, metadata) : html.replace('</title>', '</title>\n' + metadata);
  const vcard = [
    'BEGIN:VCARD', 'VERSION:3.0',
    `N:${escapeVCF(profile.lastName)};${escapeVCF(profile.firstName)};;;`,
    `FN:${escapeVCF(name)}`,
    `EMAIL;TYPE=INTERNET:${escapeVCF(profile.email)}`,
    `URL:${website.href}`,
    `X-SOCIALPROFILE;TYPE=linkedin:${profile.linkedin}`,
    'END:VCARD'
  ].map(fold).join('\r\n') + '\r\n';
  const options = {errorCorrectionLevel: 'Q', margin: 4, scale: 24, color: {dark: '#121820ff', light: '#ffffffff'}};
  await fs.writeFile(path.join(root, 'assets/dirk-herrmann.vcf'), vcard);
  await QRCode.toFile(path.join(root, 'assets/qr-dirk-herrmann.png'), website.href, options);
  await QRCode.toFile(path.join(root, 'assets/qr-dirk-herrmann.svg'), website.href, {...options, type: 'svg'});
  const data = async (file, type) => `data:${type};base64,${(await fs.readFile(path.join(root, file))).toString('base64')}`;
  const values = {
    name: escapeHTML(name), host: escapeHTML(website.hostname),
    portrait: await data('assets/hero-dirk.webp', 'image/webp'),
    sans: await data('assets/fonts/dm-sans-latin-wght-normal.woff2', 'font/woff2'),
    serif: await data('assets/fonts/dm-serif-display-latin-400-italic.woff2', 'font/woff2')
  };
  let template = await fs.readFile(path.join(root, 'templates/link-preview.html'), 'utf8');
  template = template.replace(/\{\{(\w+)\}\}/g, (_, key) => values[key]);
  const browser = await chromium.launch({executablePath: process.env.CHROMIUM_PATH || undefined, args: ['--no-sandbox']});
  try {
    const context = await browser.newContext({viewport: {width: 1200, height: 630}, deviceScaleFactor: 1});
    const page = await context.newPage();
    await page.setContent(template, {waitUntil: 'load'});
    await page.evaluate(() => document.fonts.ready);
    await page.waitForFunction(() => [...document.images].every(img => img.complete && img.naturalWidth > 0));
    await page.screenshot({path: path.join(root, 'assets/dirk-herrmann-vorschau.png')});
    await context.close();
  } finally { await browser.close(); }
  await fs.writeFile(htmlFile, html);
  console.log('QR (PNG/SVG), phone-free vCard, share image (1200×630) and metadata prepared for ' + website.href);
})().catch(error => {console.error(error);process.exitCode = 1;});
